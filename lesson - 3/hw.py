davlatlar = {
    'США':'Вашингтон',
    'Китай':'Пекин',
    'Италия':'Рим',
    'Узбекистан':'Ташкент',
    'Россия':'Москва',
    'Швейцария':'Берн',
    'Швеция':'Стокгольм',
    'Германия':'Берлин',
    'ОАЭ':'Абу-Даби',
    'Корея':'Сеул',
}

print(f"Страны в мире:")
for davlat in sorted(davlatlar.keys()):
    print(davlat)
    
print(f"Их столицы:")
for poyt in sorted(davlatlar.values()):
    print(poyt)
    
#3
user = input("Введите страну что бы узнать ее столицу: ")

if user in davlatlar:
    print(f"{user} столица: {davlatlar[user]} город")
else:
    print("У нас нету этой странны в списке")